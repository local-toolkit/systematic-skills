#!/usr/bin/env python3
"""
Auto-generate Monty external function wrapper for a skill
Usage: python generate_monty_wrapper.py <skill-name> [options]
"""

import sys
import os
from pathlib import Path


def detect_tool_type(skill_name: str) -> str:
    """Detect if skill is subprocess or MCP type."""
    skill_path = Path(f".agent/skills/{skill_name}")

    if not skill_path.exists():
        return "unknown"

    tool_dir = skill_path / "tool"

    if not tool_dir.exists():
        return "unknown"

    # Check for MCP server
    if (tool_dir / "mcp_server.py").exists():
        return "mcp"

    # Check for main.py
    if (tool_dir / "main.py").exists():
        return "subprocess"

    return "unknown"


